//! Read every mip, rather than only level zero: a clean 100% view does not prove that
//! reduced previews are valid. Keep all cases on one device (some drivers dislike concurrent
//! test devices), and use synthetic pixels instead of event photographs.

use super::*;
use photocraft_compose::Buffer;
use photocraft_doc::SampleType;
use photocraft_geom::Rect;

fn read_mips(gpu: &GpuCanvas, key: u64) -> Vec<Vec<[f32; 4]>> {
    let renderer = gpu.rs.renderer.read();
    let doc = &renderer.callback_resources.canvas(gpu.id).unwrap().docs[&key];
    assert_eq!(doc.tiles.len(), 1);
    let tile = &doc.tiles[0];
    let (device, queue) = (&gpu.rs.device, &gpu.rs.queue);
    let bpp = texel_bytes(doc.format) as usize;
    (0..tile.levels.len())
        .map(|level| {
            let (w, h) = ((doc.size[0] >> level).max(1), (doc.size[1] >> level).max(1));
            let row = (w as usize * bpp).next_multiple_of(wgpu::COPY_BYTES_PER_ROW_ALIGNMENT as usize);
            let buffer = device.create_buffer(&wgpu::BufferDescriptor {
                label: Some("mip_test_readback"),
                size: (row * h as usize) as u64,
                usage: wgpu::BufferUsages::COPY_DST | wgpu::BufferUsages::MAP_READ,
                mapped_at_creation: false,
            });
            let mut encoder = device.create_command_encoder(&Default::default());
            encoder.copy_texture_to_buffer(
                wgpu::TexelCopyTextureInfo { texture: &tile.texture, mip_level: level as u32, origin: wgpu::Origin3d::ZERO, aspect: wgpu::TextureAspect::All },
                wgpu::TexelCopyBufferInfo {
                    buffer: &buffer,
                    layout: wgpu::TexelCopyBufferLayout { offset: 0, bytes_per_row: Some(row as u32), rows_per_image: Some(h) },
                },
                wgpu::Extent3d { width: w, height: h, depth_or_array_layers: 1 },
            );
            queue.submit([encoder.finish()]);
            buffer.slice(..).map_async(wgpu::MapMode::Read, |result| result.unwrap());
            assert!(gpu.health.wait(device, None));
            let data = buffer.slice(..).get_mapped_range().unwrap();
            let mut pixels = Vec::new();
            for y in 0..h as usize {
                for x in 0..w as usize {
                    let offset = y * row + x * bpp;
                    pixels.push(texel_to_f32(doc.format, &data[offset..offset + bpp]));
                }
            }
            pixels
        })
        .collect()
}

#[test]
fn canvas_mips_preserve_opaque_pixels_and_partial_updates() {
    let rs = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| egui_kittest::wgpu::create_render_state(wgpu_setup(), Default::default())));
    let Ok(rs) = rs else {
        eprintln!("skipping mip readback: no GPU adapter");
        return;
    };
    eprintln!("mip readback adapter: {:?}", rs.adapter.get_info());
    let gpu = GpuCanvas::new(&rs);
    // Both mip paths: straight into the level, and the DX12 scratch-texture workaround.
    for separate in [false, true] {
        gpu.rs.renderer.write().callback_resources.canvas_mut(gpu.id).unwrap().separate_mip_targets = separate;
        check_mips(&gpu);
        check_refinement_pieces(&gpu);
    }
    check_viewport_pages(&gpu);
}

/// A large edit seen zoomed out is composited at a reduced level, then brought to full size a
/// piece of rows at a time. Each piece's coarser levels must not average in the full-size pixels
/// below it, which nothing has composited yet: on a white page they showed as a faint dashed
/// line (the checkerboard through half-transparent texels) until refinement finished.
fn check_refinement_pieces(gpu: &GpuCanvas) {
    use photocraft_doc::{ColorMode, Document, Layer, Size};
    let (w, h) = (800u32, 800u32);
    let mut doc = Document::new("refine", Size::new(w, h), ColorMode::Rgb, SampleType::U8);
    let mut l = Layer::raster("white", doc.pixel_format());
    l.surface_mut().unwrap().fill_rect(Rect::new(0, 0, w as i32, h as i32), &[1.0, 1.0, 1.0, 1.0]);
    doc.layers.push(l);
    // A fresh texture set that gets the edit at level 1 only: level 0 holds nothing yet.
    gpu.composite_lod(&doc, doc.bounds(), false, 1, true).unwrap();
    assert!(!gpu.sharp_in(doc.id.0, doc.bounds()), "reduced: not sharp");
    let mut y = 0;
    for rows in [37, 64, 99] {
        gpu.composite_lod(&doc, Rect::new(0, y, w as i32, y + rows), false, 0, true).unwrap();
        y += rows;
        for (level, pixels) in read_mips(gpu, doc.id.0).iter().enumerate().skip(1) {
            let lw = (w >> level).max(1) as usize;
            for (i, p) in pixels.iter().enumerate() {
                assert!((p[3] - 1.0).abs() < 0.01, "full size up to row {y}: mip {level} texel {:?} is {p:?}", (i % lw, i / lw));
            }
        }
    }
    // The rest in uneven pieces: once all of it is full size, every level is the white page
    // (the texels left at the piece edges were regenerated by the pieces after them).
    while y < h as i32 {
        let rows = 75.min(h as i32 - y);
        gpu.composite_lod(&doc, Rect::new(0, y, w as i32, y + rows), false, 0, true).unwrap();
        y += rows;
    }
    for (level, pixels) in read_mips(gpu, doc.id.0).iter().enumerate() {
        assert!(pixels.iter().all(|p| p.iter().all(|c| (c - 1.0).abs() < 0.01)), "mip {level} after full refinement");
    }
    assert!(gpu.sharp_in(doc.id.0, doc.bounds()), "all full size: sharp");
}

fn check_mips(gpu: &GpuCanvas) {
    for depth in [SampleType::U8, SampleType::U16, SampleType::F32] {
        for (w, h) in [(1791, 1083), (513, 1), (1, 513)] {
            let mut full = Buffer::filled(Rect::from_xywh(0, 0, w, h), [0.25, 0.5, 0.75, 1.0]);
            // Reusing the key also covers replacing textures after a size or depth change.
            gpu.upload_buffer_full(1, &full, depth);
            for (level, pixels) in read_mips(gpu, 1).iter().enumerate() {
                for pixel in pixels {
                    assert!((pixel[3] - 1.0).abs() < 0.001, "{depth:?} {w}x{h} mip {level}: {pixel:?}");
                    for (actual, expected) in pixel.iter().zip([0.25, 0.5, 0.75, 1.0]) {
                        assert!((actual - expected).abs() < 0.005, "{depth:?} {w}x{h} mip {level}: {pixel:?}");
                    }
                }
            }
            let patch = Rect::from_xywh((w / 2) as i32, (h / 2) as i32, (w / 3).max(1), (h / 3).max(1));
            let changed = Buffer::filled(patch, [1.0, 0.0, 0.0, 1.0]);
            assert!(gpu.upload_buffer_rect(1, &changed));
            for y in patch.y0..patch.y1 {
                for x in patch.x0..patch.x1 {
                    full.px[y as usize * w as usize + x as usize] = [1.0, 0.0, 0.0, 1.0];
                }
            }
            gpu.upload_buffer_full(2, &full, depth);
            let partial = read_mips(gpu, 1);
            let rebuilt = read_mips(gpu, 2);
            for (level, (actual, expected)) in partial.iter().zip(&rebuilt).enumerate() {
                for (a, b) in actual.iter().zip(expected) {
                    assert!((a[3] - 1.0).abs() < 0.001, "partial {depth:?} mip {level}: {a:?}");
                    for (a, b) in a.iter().zip(b) {
                        assert!((a - b).abs() < 0.005, "partial/full mismatch {depth:?} {w}x{h} mip {level}: {a} != {b}");
                    }
                }
            }
        }
    }
}

/// #5332: a page's GPU bytes are its texture's, not its document area's; a refused page fails
/// alone (its work inside error scopes, so it can't take the GPU down) and an accepted one is
/// stored, updated in part and dropped.
fn check_viewport_pages(gpu: &GpuCanvas) {
    let device = &gpu.rs.device;
    let max = device.limits().max_texture_dimension_2d;
    let (texture, error) = pages::catch_gpu_errors(device, || {
        device.create_texture(&wgpu::TextureDescriptor {
            label: Some("too_wide_page"),
            size: wgpu::Extent3d { width: max + 1, height: 1, depth_or_array_layers: 1 },
            mip_level_count: 1,
            sample_count: 1,
            dimension: wgpu::TextureDimension::D2,
            format: FORMAT,
            usage: wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::COPY_DST,
            view_formats: &[],
        })
    });
    drop(texture);
    assert!(error.is_some(), "the refusal is caught");
    assert!(gpu.health.is_ok(), "{:?}", gpu.fault());
    // What the checks before this one left is not this page's to count.
    gpu.retain(&[]);
    let before = gpu.held_bytes();
    gpu.set_canvas_budget(1 << 20);
    // Texels 64 x 64 at a reduction of 4: 16 KiB, though it draws 256 x 256 document pixels.
    let buf = Buffer::filled(Rect::from_xywh(0, 0, 64, 64), [0.5, 0.5, 0.5, 1.0]);
    let page = |page, buf| PageUpload { key: 9, page, size: [256, 256], depth: SampleType::U8, factor: 4, core: Rect::new(0, 0, 256, 256), buf };
    assert!(gpu.upload_page(page(1, &buf)));
    assert_eq!(gpu.pages(9), (vec![1], 64 * 64 * 4));
    assert_eq!(gpu.held_bytes() - before, 64 * 64 * 4, "the display sets' sum counts the page's texture");
    assert!(gpu.update_page(9, 1, &Buffer::filled(Rect::from_xywh(2, 2, 3, 3), [1.0, 0.0, 0.0, 1.0])));
    assert!(!gpu.update_page(9, 1, &Buffer::filled(Rect::from_xywh(63, 0, 3, 3), [1.0, 0.0, 0.0, 1.0])), "outside the page");
    assert!(!gpu.update_page(9, 2, &buf), "not held");
    // Over the budget, a page is refused and nothing changes.
    gpu.set_canvas_budget(64 * 64 * 4);
    assert!(!gpu.upload_page(page(2, &buf)));
    assert_eq!(gpu.pages(9).0, vec![1]);
    // Another document's texture set gives way to a page; the page's own document doesn't.
    gpu.set_canvas_budget(1 << 20);
    gpu.upload_buffer_full(5, &Buffer::filled(Rect::from_xywh(0, 0, 400, 400), [0.0, 0.0, 0.0, 1.0]), SampleType::U8);
    assert!(gpu.texture_info(5).is_some());
    let big = Buffer::filled(Rect::from_xywh(0, 0, 500, 500), [0.0, 0.0, 0.0, 1.0]);
    assert!(gpu.upload_page(page(3, &big)));
    assert!(gpu.texture_info(5).is_none());
    assert_eq!(gpu.pages(9).0.len(), 2);
    gpu.retain_pages(9, &[3]);
    assert_eq!(gpu.pages(9).0, vec![3]);
    gpu.retain_pages(9, &[]);
    assert_eq!(gpu.pages(9).1, 0);
    assert!(gpu.health.is_ok(), "{:?}", gpu.fault());
}
