//! GPU document canvas: an `egui_wgpu` paint callback that draws one document view with a custom
//! WGSL shader.
//!
//! The document's composite lives on the GPU as one or more mipmapped textures (premultiplied
//! alpha, sRGB-encoded values, matching how the CPU path and egui blend): `Rgba8Unorm` for 8-bit
//! documents, `Rgba16Float` for 16- and 32-bit documents when the adapter can render to and
//! filter it (so smooth gradients don't band and 32-bit values above 1.0 survive for the 32-bit
//! preview), within [`F16_BUDGET_PX`]; larger high-bit documents fall back to `Rgba8Unorm`.
//! Uploads are either full (new document, size change, re-render) or a damage rect (brush
//! strokes); after an upload only the affected region of each mip level is regenerated by a
//! render-pass blit chain. Documents larger than the device's maximum texture size are split
//! into tiles.
//!
//! Per frame the shader draws, in *device pixels*:
//! - a soft analytic drop shadow around the document on the pasteboard (erf-blurred box),
//! - a transparency checkerboard (8 pt squares, grays 255/204, the same size at every zoom)
//!   under the document, anchored to the document's top-left corner so it moves with the image,
//! - the document itself, sampled trilinearly when zoomed out, bilinearly between 1× and 2×, and
//!   with an anti-aliased "sharp nearest" filter at integer scales and ≥ 2×,
//! - a one-device-pixel pixel grid above 500% zoom, over pixels with content only.
//!
//! GPU resources live in the renderer's `callback_resources` type map; the per-frame callback only
//! carries plain view parameters, so it is `Send + Sync` on every target (including wasm).
//!
//! The document pixels still come from the CPU compositor (`photocraft-compose`) for now; the wgpu
//! compositor (M5) will render straight into these tiles.

use std::collections::HashMap;
use std::num::NonZeroU64;

use eframe::egui_wgpu::{self, CallbackResources, CallbackTrait, RenderState, ScreenDescriptor};
use eframe::wgpu;

pub use photocraft_gpu::{DeviceHealth, Fault};

/// Default tile side; documents up to this size (and the device limit) use a single texture.
pub const DEFAULT_TILE: u32 = 8192;
const FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Rgba8Unorm;
/// Canvas texture format of high-bit documents (see [`GpuCanvas::format_for`]).
const FORMAT_HIGH: wgpu::TextureFormat = wgpu::TextureFormat::Rgba16Float;
/// Largest high-bit document (in pixels) given an `Rgba16Float` canvas texture: 100 MP is
/// 800 MB at level 0, about 1.07 GB with mips (twice the `Rgba8Unorm` cost). Bigger 16/32-bit
/// documents (a 14000² one would need 2.1 GB) use `Rgba8Unorm`, so they stay on the GPU like
/// 8-bit ones. `PHOTOCRAFT_CANVAS_F16=0` turns the float canvas off, `=1` ignores this budget.
pub const F16_BUDGET_PX: u64 = 100_000_000;
const VIEW_UNIFORM_SIZE: u64 = 128;
const VIEW_FLOATS: usize = 32;
const TILE_UNIFORM_SIZE: u64 = 16;

/// Whether this view can use the GPU canvas. Flip and non-square pixel aspect correction are
/// still CPU blits (the shader's filtering assumes square pixels); rotation is a shader uniform.
pub fn gpu_view_ok(flip: bool, _rotation: f32, aspect: f32) -> bool {
    !flip && (aspect - 1.0).abs() < 1e-6
}

/// Parameters for drawing one document view. Positions are in egui points.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ViewParams {
    /// Document key used with [`GpuCanvas::upload_full`].
    pub doc: u64,
    /// Document size in pixels.
    pub doc_size: [u32; 2],
    /// Screen points per document pixel.
    pub zoom: f32,
    /// Document point shown at the centre of the canvas rect.
    pub center: [f32; 2],
    /// Camera rotation in radians, clockwise in Y-down screen space. Rotate around [`Self::center`]
    /// before sampling. Flip stays on the CPU path.
    pub rotation: f32,
    /// Draw the drop shadow on the pasteboard.
    pub shadow: bool,
    /// Draw the pixel grid at high zoom.
    pub pixel_grid: bool,
    /// Distinguishes views painted in the same frame (main canvas, extra windows).
    pub view_key: u64,
    /// Display transform: 0 none, 1 the document's display LUT (document → monitor profile,
    /// Proof Colors), 2 LUT plus the gamut warning (see [`GpuCanvas::set_display_lut`]).
    pub display: u8,
    /// The display the view is on (its LUT is per document and display, #569; 0 = unknown).
    pub output: u32,
    /// View › 32-bit Preview Options (exposure in stops, gamma), applied to the texture values
    /// before the display LUT; `None` when off. The display LUT must then leave it out
    /// (`ColorState::gpu_canvas_lut`).
    pub hdr: Option<[f32; 2]>,
    /// Where this draw puts the document, in document pixels from its own place: `[0, 0]` for the
    /// document, a whole number of widths and heights for a View › Pattern Preview copy (#1067).
    /// A copy samples the same texture, so nothing is composited again.
    pub offset: [f32; 2],
    /// Sample no finer mip level than this (trilinear): set while what the view shows was
    /// composited reduced and is waiting for full size (see [`GpuCanvas::view_floor`]).
    pub min_lod: f32,
}

/// When high-bit documents get an `Rgba16Float` canvas texture.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum HighPolicy {
    /// The adapter can't render to or filter `Rgba16Float`, or `PHOTOCRAFT_CANVAS_F16=0`.
    Off,
    /// Up to [`F16_BUDGET_PX`].
    Budget,
    /// Always (`PHOTOCRAFT_CANVAS_F16=1`).
    Always,
}

/// Uploads documents to the GPU and paints them. Cheap to clone.
///
/// Once the device is lost or reports an uncaptured error (see [`GpuCanvas::fault`]), every
/// method is a no-op or an `Err`, so nothing reaches the GPU again; the app then switches to the
/// CPU canvas (#243).
#[derive(Clone)]
pub struct GpuCanvas {
    rs: RenderState,
    tile: u32,
    high: HighPolicy,
    health: photocraft_gpu::DeviceHealth,
    /// Paces [`GpuCanvas::catch_up`]'s full-size refinement by GPU completion.
    refine: RefinePacer,
    /// Composites submitted and completed (see [`GpuCanvas::busy`]).
    pace: CompositePacer,
}

/// At most one document composite queued on the GPU: while one runs, the next frame's edit is
/// left for later ([`GpuCanvas::defer`]) instead of queueing behind it, so the frame that does
/// composite shows the latest input (a GPU-bound page otherwise falls frames behind the pointer).
#[derive(Clone, Default)]
struct CompositePacer {
    submitted: std::sync::Arc<std::sync::atomic::AtomicU64>,
    done: std::sync::Arc<std::sync::atomic::AtomicU64>,
    /// When the last one was submitted ([`now_ms`] bits).
    at: std::sync::Arc<std::sync::atomic::AtomicU64>,
}

/// Whether the canvas leaves an edit for the next frame while the last composite still runs
/// (`CompositePacer`). Off: on WebGL the completion callbacks arrive late, and deferring stalled
/// brush strokes for seconds (headless SwiftShader: 2 frames per stroke instead of 10).
pub const PACE_COMPOSITES: bool = false;

/// How long a composite may stay unfinished before the next goes anyway (a lost completion
/// callback never stalls the canvas).
pub const BUSY_LIMIT_MS: f64 = 250.0;

impl CompositePacer {
    fn submitted(&self, queue: &wgpu::Queue) {
        use std::sync::atomic::Ordering::Relaxed;
        let token = self.submitted.fetch_add(1, Relaxed) + 1;
        self.at.store(now_ms().to_bits(), Relaxed);
        let done = self.done.clone();
        queue.on_submitted_work_done(move || {
            done.fetch_max(token, Relaxed);
        });
    }

    fn busy(&self) -> bool {
        use std::sync::atomic::Ordering::Relaxed;
        self.done.load(Relaxed) < self.submitted.load(Relaxed) && now_ms() - f64::from_bits(self.at.load(Relaxed)) < BUSY_LIMIT_MS
    }
}

/// One refinement piece in flight at a time; the work per piece (output pixels × passes) adapts
/// to the GPU time the last piece took, aiming for about [`REFINE_TARGET_MS`].
#[derive(Clone)]
struct RefinePacer {
    /// Milliseconds the last piece took from submit to completion (`f64` bits; `u64::MAX`
    /// while it runs, `u64::MAX - 1` before the first).
    last: std::sync::Arc<std::sync::atomic::AtomicU64>,
    work: std::sync::Arc<std::sync::atomic::AtomicU64>,
    /// When the GPU finished what was queued before the current piece ([`now_ms`] bits): the
    /// piece's own time starts there (or at its submit, if the GPU was idle), not behind the
    /// frames queued before it.
    before: std::sync::Arc<std::sync::atomic::AtomicU64>,
}

/// GPU time one refinement piece aims for (ms).
pub const REFINE_TARGET_MS: f64 = 8.0;

impl RefinePacer {
    const RUNNING: u64 = u64::MAX;
    const IDLE: u64 = u64::MAX - 1;

    fn new() -> Self {
        Self { last: std::sync::Arc::new(Self::IDLE.into()), work: std::sync::Arc::new(REFINE_WORK.into()), before: std::sync::Arc::new(0u64.into()) }
    }

    /// Whether a piece is still on the GPU, and the work the next may take.
    fn next_work(&self) -> (bool, u64) {
        use std::sync::atomic::Ordering::Relaxed;
        let last = self.last.load(Relaxed);
        let mut work = self.work.load(Relaxed);
        if last == Self::RUNNING {
            return (true, work);
        }
        if last != Self::IDLE {
            let ms = f64::from_bits(last);
            // Towards the target: down at once on a slow GPU, up at most doubling per piece.
            let k = (REFINE_TARGET_MS / ms.max(0.25)).clamp(1.0 / 16.0, 2.0);
            work = ((work as f64 * k) as u64).clamp(REFINE_WORK / 64, REFINE_WORK * 16);
            self.work.store(work, Relaxed);
            self.last.store(Self::IDLE, Relaxed);
        }
        (false, work)
    }

    /// Before a piece is recorded: the returned callback (for `on_submitted_work_done`) notes
    /// when the work queued so far is done.
    fn before(&self) -> impl FnOnce() + Send + 'static {
        use std::sync::atomic::Ordering::Relaxed;
        self.before.store(f64::NAN.to_bits(), Relaxed);
        let before = self.before.clone();
        move || before.store(now_ms().to_bits(), Relaxed)
    }

    /// Mark a piece submitted; the returned callback (for `on_submitted_work_done`) records how
    /// long the GPU spent on it.
    fn start(&self) -> impl FnOnce() + Send + 'static {
        use std::sync::atomic::Ordering::Relaxed;
        self.last.store(Self::RUNNING, Relaxed);
        let (last, before) = (self.last.clone(), self.before.clone());
        let t0 = now_ms();
        move || {
            let b = f64::from_bits(before.load(Relaxed));
            let from = if b.is_finite() { b.max(t0) } else { t0 };
            last.store((now_ms() - from).max(0.0).to_bits(), Relaxed);
        }
    }
}

/// Can `adapter` use `Rgba16Float` as a sampled, filtered, render-target and copy texture?
/// (Core WebGPU guarantees it; WebGL2 needs `EXT_color_buffer_float`, and some drivers lack it.)
pub fn supports_f16_canvas(adapter: &wgpu::Adapter) -> bool {
    let f = adapter.get_texture_format_features(FORMAT_HIGH);
    let usages = wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::RENDER_ATTACHMENT | wgpu::TextureUsages::COPY_DST | wgpu::TextureUsages::COPY_SRC;
    f.allowed_usages.contains(usages) && f.flags.contains(wgpu::TextureFormatFeatureFlags::FILTERABLE)
}

impl GpuCanvas {
    /// Create pipelines and register resources with the egui renderer.
    pub fn new(rs: &RenderState) -> Self {
        Self::with_tile(rs, None)
    }

    /// Like [`GpuCanvas::new`] with a preferred texture tile side (`PHOTOCRAFT_GPU_TILE` wins).
    pub fn with_tile(rs: &RenderState, tile: Option<u32>) -> Self {
        let max = rs.device.limits().max_texture_dimension_2d;
        let env_tile = std::env::var("PHOTOCRAFT_GPU_TILE").ok().and_then(|v| v.parse::<u32>().ok());
        let tile = env_tile.or(tile).unwrap_or(DEFAULT_TILE).clamp(64, max);
        let high = match std::env::var("PHOTOCRAFT_CANVAS_F16").ok().as_deref() {
            _ if !supports_f16_canvas(&rs.adapter) => HighPolicy::Off,
            Some("0") => HighPolicy::Off,
            Some("1") => HighPolicy::Always,
            _ => HighPolicy::Budget,
        };
        // Device loss and uncaptured errors mark this flag instead of panicking (#243).
        let health = photocraft_gpu::DeviceHealth::watch(&rs.device);
        let mut res = Resources::new(&rs.device, &rs.queue, rs.target_format, high != HighPolicy::Off);
        res.health = health.clone();
        res.separate_mip_targets = rs.adapter.get_info().backend == wgpu::Backend::Dx12;
        rs.renderer.write().callback_resources.insert(stored(res));
        log::info!("gpu canvas: target {:?}, max texture {max}, tile {tile}, 16F canvas {high:?}", rs.target_format);
        Self { rs: rs.clone(), tile, high, health, refine: RefinePacer::new(), pace: CompositePacer::default() }
    }

    /// Run `done` once the GPU has finished everything submitted so far. False once the device
    /// is lost.
    pub fn on_done(&self, done: impl FnOnce() + Send + 'static) -> bool {
        if !self.health.is_ok() {
            return false;
        }
        self.rs.queue.on_submitted_work_done(done);
        true
    }

    /// The device's health flag (shared with the wgpu compositor and the paint callback).
    pub fn health(&self) -> &photocraft_gpu::DeviceHealth {
        &self.health
    }

    /// Why the GPU can't be used any more (`None` while it can).
    pub fn fault(&self) -> Option<photocraft_gpu::Fault> {
        self.health.fault()
    }

    /// Free every GPU resource the canvas holds (compositor pages, document textures, LUTs) after
    /// a fault; the paint callback draws nothing from then on.
    pub fn release(&self) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<StoredResources>() {
            res.compositor = None;
            res.compositor_failed = Some(photocraft_gpu::Unsupported(self.fault().map_or_else(|| "GPU canvas released".into(), |f| f.to_string())));
            res.docs.clear();
            res.luts.clear();
            res.display_lut_signatures.clear();
            res.views.clear();
        }
    }

    /// The adapter this canvas renders with.
    pub fn adapter_info(&self) -> wgpu::AdapterInfo {
        self.rs.adapter.get_info()
    }

    /// The canvas texture format for a document of `depth` and `size`: `Rgba16Float` for 16/32-bit
    /// documents when the adapter supports it and the document fits [`F16_BUDGET_PX`], else
    /// `Rgba8Unorm`.
    /// The device's largest 2D texture side (egui textures can use it too).
    pub fn max_texture_side(&self) -> usize {
        self.rs.device.limits().max_texture_dimension_2d as usize
    }

    pub fn format_for(&self, depth: photocraft_doc::SampleType, size: [u32; 2]) -> wgpu::TextureFormat {
        let px = size[0] as u64 * size[1] as u64;
        let high = match self.high {
            HighPolicy::Off => false,
            HighPolicy::Budget => px <= F16_BUDGET_PX,
            HighPolicy::Always => true,
        };
        if high && depth != photocraft_doc::SampleType::U8 { FORMAT_HIGH } else { FORMAT }
    }

    /// Format and GPU bytes (all tiles, all mip levels) of document `key`'s canvas texture.
    pub fn texture_info(&self, key: u64) -> Option<(wgpu::TextureFormat, u64)> {
        let r = self.rs.renderer.read();
        let d = r.callback_resources.get::<StoredResources>()?.docs.get(&key)?;
        let bpp = texel_bytes(d.format);
        let bytes = d
            .tiles
            .iter()
            .map(|t| (0..t.levels.len() as u32).map(|l| ((t.rect[2] >> l).max(1) as u64) * ((t.rect[3] >> l).max(1) as u64) * bpp).sum::<u64>())
            .sum();
        Some((d.format, bytes))
    }

    /// Set the GPU memory the wgpu compositor may hold for layer pages and caches (see
    /// [`memory_budget`]); pages beyond it are evicted least recently used first.
    pub fn set_memory_budget(&self, bytes: u64) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<StoredResources>() {
            res.compositor_budget = Some(bytes);
        }
    }

    /// The compositor's memory budget (`None` until [`GpuCanvas::set_memory_budget`]).
    pub fn memory_budget(&self) -> Option<u64> {
        let r = self.rs.renderer.read();
        r.callback_resources.get::<StoredResources>()?.compositor_budget
    }

    /// Set the GPU bytes one document's display texture set may take (see [`canvas_budget`]).
    pub fn set_canvas_budget(&self, bytes: u64) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<StoredResources>() {
            res.canvas_budget = bytes;
        }
    }

    /// Whether `doc`'s display textures fit [`canvas_budget`]; when they don't, nothing is
    /// created for it and it is drawn on the CPU canvas.
    pub fn fits_canvas(&self, doc: &photocraft_doc::Document) -> bool {
        let size = [doc.size.width, doc.size.height];
        let bytes = canvas_texture_bytes(size, self.tile, texel_bytes(self.format_for(doc.depth, size)));
        let r = self.rs.renderer.read();
        r.callback_resources.get::<StoredResources>().is_some_and(|res| bytes <= res.canvas_budget)
    }

    /// Cap lower-stack composite reuse; zero disables it for profiling the uncached path.
    pub fn set_composite_cache_budget(&self, bytes: u64) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<StoredResources>() {
            res.compositor_cache_budget = Some(bytes);
            if let Some(comp) = &mut res.compositor {
                comp.set_composite_cache_budget(bytes);
            }
        }
    }

    /// Layers the next refreshes draw from their already resident pre-move surface at an offset
    /// (a Move drag's preview), instead of uploading the moved copy every frame. Empty: none.
    pub fn set_translated(&self, translated: Vec<photocraft_gpu::Translated>) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<StoredResources>()
            && (!translated.is_empty() || !res.compositor_translated.is_empty())
        {
            res.compositor_translated = translated;
        }
    }

    /// The document area the view shows: full refreshes composite it last, so its layer pages
    /// are the ones still resident for the edits that follow.
    pub fn set_focus(&self, focus: Option<photocraft_geom::Rect>) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<StoredResources>() {
            res.compositor_focus = focus;
        }
    }

    /// GPU bytes the wgpu compositor holds: resident layer pages and caches (effect maps and
    /// lower-stack chunks). Keep the scorecard's memory measurements inclusive of reuse.
    pub fn compositor_bytes(&self) -> Option<(u64, usize)> {
        let r = self.rs.renderer.read();
        let c = r.callback_resources.get::<StoredResources>()?.compositor.as_ref()?;
        Some((c.resident_bytes(), c.fx_cache_bytes().saturating_add(usize::try_from(c.composite_cache_bytes()).unwrap_or(usize::MAX))))
    }

    /// Set the checkerboard and gamut warning colours.
    pub fn set_style(&self, style: CanvasStyle) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<StoredResources>() {
            res.style = style;
        }
    }

    /// Whether document `doc` has been uploaded with this size.
    pub fn has(&self, doc: u64, size: [u32; 2]) -> bool {
        let r = self.rs.renderer.read();
        r.callback_resources.get::<StoredResources>().and_then(|res| res.docs.get(&doc)).is_some_and(|d| d.size == size)
    }

    /// Whether [`GpuCanvas::composite`] would draw `doc` with the wgpu compositor (rather than
    /// fall back to the CPU compositor).
    pub fn supports(&self, doc: &photocraft_doc::Document) -> bool {
        if std::env::var_os("PHOTOCRAFT_CPU_COMPOSE").is_some() || doc.size.width == 0 || doc.size.height == 0 {
            return false;
        }
        let r = self.rs.renderer.read();
        let Some(res) = r.callback_resources.get::<StoredResources>() else { return false };
        if res.compositor_failed.is_some() {
            return false;
        }
        match &res.compositor {
            Some(c) => c.supports(doc).is_ok(),
            // Layers larger than the texture limit are stored in pages, so any size qualifies.
            None => photocraft_gpu::plan(doc).is_ok(),
        }
    }

    /// Replace the whole document image with an `Rgba8Unorm` texture. `rgba` is premultiplied
    /// RGBA8, `size[0] * size[1] * 4` bytes (anything else is ignored).
    pub fn upload_full(&self, doc: u64, size: [u32; 2], rgba: &[u8]) {
        self.upload_full_as(doc, size, FORMAT, rgba);
    }

    /// Replace the whole document image with a `format` texture of premultiplied `texels`.
    fn upload_full_as(&self, doc: u64, size: [u32; 2], format: wgpu::TextureFormat, texels: &[u8]) {
        if size[0] == 0 || size[1] == 0 || texels.len() as u64 != size[0] as u64 * size[1] as u64 * texel_bytes(format) || !self.health.is_ok() {
            return;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<StoredResources>() else { return };
        if res.docs.get(&doc).is_none_or(|d| d.size != size || d.format != format) {
            let Some(tex) = DocTextures::new(device, res, size, self.tile, format) else {
                res.docs.remove(&doc);
                return;
            };
            res.docs.insert(doc, tex);
        }
        let Some(d) = res.docs.get(&doc) else { return };
        d.write(queue, [0, 0], size, size[0], texels);
        d.regenerate_mips(device, queue, res, [0, 0, size[0], size[1]]);
    }

    /// Replace a rectangle `origin..origin+size` of an uploaded document with premultiplied texels
    /// in its texture format (`size[0] * size[1]` texels: RGBA8 or RGBA16F). Returns false if the
    /// document isn't uploaded, the rectangle doesn't fit or the buffer has the wrong size.
    pub fn upload_rect(&self, doc: u64, origin: [u32; 2], size: [u32; 2], texels: &[u8]) -> bool {
        if !self.health.is_ok() {
            return false;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<StoredResources>() else { return false };
        let Some(d) = res.docs.get(&doc) else { return false };
        if texels.len() as u64 != size[0] as u64 * size[1] as u64 * texel_bytes(d.format)
            || origin[0].saturating_add(size[0]) > d.size[0]
            || origin[1].saturating_add(size[1]) > d.size[1]
        {
            return false;
        }
        if size[0] == 0 || size[1] == 0 {
            return true;
        }
        d.write(queue, origin, size, size[0], texels);
        d.regenerate_mips(device, queue, res, [origin[0], origin[1], origin[0] + size[0], origin[1] + size[1]]);
        true
    }

    /// The texture format of uploaded document `doc`.
    fn format_of(&self, doc: u64) -> Option<wgpu::TextureFormat> {
        let r = self.rs.renderer.read();
        r.callback_resources.get::<StoredResources>().and_then(|res| res.docs.get(&doc)).map(|d| d.format)
    }

    /// Upload a CPU composite covering the whole document (a preview of a document of `depth`:
    /// see [`GpuCanvas::format_for`]).
    pub fn upload_buffer_full(&self, doc: u64, buf: &photocraft_compose::Buffer, depth: photocraft_doc::SampleType) {
        let size = [buf.rect.width(), buf.rect.height()];
        let format = self.format_for(depth, size);
        self.upload_full_as(doc, size, format, &texels(format, &buf.px));
    }

    /// Upload a CPU composite of a sub-rectangle (in document pixels, `buf.rect`).
    pub fn upload_buffer_rect(&self, doc: u64, buf: &photocraft_compose::Buffer) -> bool {
        let r = buf.rect;
        let Some(format) = self.format_of(doc) else { return false };
        if r.x0 < 0 || r.y0 < 0 {
            return false;
        }
        self.upload_rect(doc, [r.x0 as u32, r.y0 as u32], [r.width(), r.height()], &texels(format, &buf.px))
    }

    /// Composite `region` of `doc` with the wgpu compositor straight into its display texture
    /// (no CPU pixels, no upload of the composite). `encode_srgb` stores the sRGB encoding of the
    /// composite (linear documents, see `photocraft_engine::display_color`). Returns `Err` when the
    /// document uses features the GPU compositor doesn't cover yet; the caller then falls back to
    /// the CPU compositor.
    pub fn composite(
        &self,
        doc: &photocraft_doc::Document,
        region: photocraft_geom::Rect,
        encode_srgb: bool,
    ) -> Result<photocraft_gpu::Stats, photocraft_gpu::Unsupported> {
        self.composite_lod(doc, region, encode_srgb, 0, false)
    }

    /// [`GpuCanvas::composite`] at mip level `level` (`photocraft_gpu::Compositor::render_lod`):
    /// the region's finer levels are then out of date until a full-size refresh (see
    /// [`GpuCanvas::catch_up`]). `partial`: a new texture set gets only `region` (the rest is
    /// marked deferred) instead of the whole document.
    pub fn composite_lod(
        &self,
        doc: &photocraft_doc::Document,
        region: photocraft_geom::Rect,
        encode_srgb: bool,
        level: u32,
        partial: bool,
    ) -> Result<photocraft_gpu::Stats, photocraft_gpu::Unsupported> {
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let size = [doc.size.width, doc.size.height];
        if size[0] == 0 || size[1] == 0 {
            return Err(photocraft_gpu::Unsupported("empty document".into()));
        }
        if std::env::var_os("PHOTOCRAFT_CPU_COMPOSE").is_some() {
            return Err(photocraft_gpu::Unsupported("disabled by PHOTOCRAFT_CPU_COMPOSE".into()));
        }
        if let Some(f) = self.fault() {
            return Err(photocraft_gpu::Unsupported(f.to_string()));
        }
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<StoredResources>() else { return Err(photocraft_gpu::Unsupported("no GPU canvas".into())) };
        // A driver that couldn't build the pipelines once won't later: stay on the CPU compositor.
        if let Some(e) = &res.compositor_failed {
            return Err(e.clone());
        }
        let mut comp = match res.compositor.take() {
            Some(c) => c,
            None => match photocraft_gpu::Compositor::try_new_with_format(device, photocraft_gpu::Compositor::preferred_acc_format(&self.rs.adapter)) {
                Ok(c) => c,
                Err(e) => {
                    log::warn!("{e}; using the CPU compositor");
                    res.compositor_failed = Some(e.clone());
                    return Err(e);
                }
            },
        };
        comp.set_health(self.health.clone());
        if let Some(b) = res.compositor_budget {
            comp.set_memory_budget(b);
        }
        if let Some(b) = res.compositor_cache_budget {
            comp.set_composite_cache_budget(b);
        }
        comp.set_focus(res.compositor_focus);
        comp.set_translated(res.compositor_translated.clone());
        let key = doc.id.0;
        let format = self.format_for(doc.depth, size);
        let fresh = res.docs.get(&key).is_none_or(|d| d.size != size || d.format != format);
        let region = if fresh && !partial { doc.bounds() } else { region.intersect(&doc.bounds()) };
        // Checked before allocating a new canvas texture only: `render` plans (and refuses) itself.
        if fresh && let Err(e) = comp.supports(doc) {
            res.compositor = Some(comp);
            return Err(e);
        }
        // A full refresh whose layer pages don't fit the memory budget would re-upload the
        // evicted ones every time (no faster than the CPU, and more memory): the banded CPU
        // compositor does it, and edits in the view (damage rects) stay on the GPU.
        if region == doc.bounds() && !comp.fits_budget(doc, region) {
            res.compositor = Some(comp);
            return Err(photocraft_gpu::Unsupported(OVER_BUDGET.into()));
        }
        if fresh {
            let Some(tex) = DocTextures::new(device, res, size, self.tile, format) else {
                res.docs.remove(&key);
                res.compositor = Some(comp);
                return Err(photocraft_gpu::Unsupported(OVER_CANVAS_BUDGET.into()));
            };
            res.docs.insert(key, tex);
        }
        let (Some(pipe), Some(d)) = (res.encode_pipeline(format), res.docs.get(&key)) else {
            res.compositor = Some(comp);
            return Err(photocraft_gpu::Unsupported(format!("no {format:?} canvas texture or pipeline")));
        };
        let bgl = &res.encode_bgl;
        // A float canvas keeps values above 1.0 (32-bit documents, for the 32-bit preview).
        let keep_hdr = i32::from(format == FORMAT_HIGH);
        // Every tile must have the level (tiny edge tiles have short mip chains), and tiles must
        // start on whole reduced pixels.
        let mut level = level.min(d.max_level()).min(photocraft_gpu::MAX_LOD);
        while level > 0 && d.tiles.iter().any(|t| t.rect[0] % (1 << level) != 0 || t.rect[1] % (1 << level) != 0) {
            level -= 1;
        }
        // Last-resort guard: a wgpu panic (e.g. polling a device lost mid-refresh) marks the
        // device lost instead of taking the app and its documents down.
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            comp.render_lod(device, queue, doc, region, level, |enc, out| {
                for t in &d.tiles {
                    let l = out.level;
                    let Some(target) = t.levels.get(l as usize) else { continue };
                    // The tile at the chunk's level (tile origins are multiples of the tile side).
                    let [tx, ty, tw, th] = [t.rect[0] >> l, t.rect[1] >> l, (t.rect[2] >> l).max(1), (t.rect[3] >> l).max(1)].map(|v| v as i32);
                    let r = out.rect.intersect(&photocraft_geom::Rect::from_xywh(tx, ty, tw as u32, th as u32));
                    if r.is_empty() {
                        continue;
                    }
                    let offset = [out.rect.x0 - tx - out.origin[0] as i32, out.rect.y0 - ty - out.origin[1] as i32, i32::from(encode_srgb), keep_hdr];
                    let ubuf = init_buffer(device, "pc_encode", &offset.iter().flat_map(|v| v.to_le_bytes()).collect::<Vec<u8>>(), wgpu::BufferUsages::UNIFORM);
                    let bg = device.create_bind_group(&wgpu::BindGroupDescriptor {
                        label: Some("pc_encode"),
                        layout: bgl,
                        entries: &[
                            wgpu::BindGroupEntry { binding: 0, resource: wgpu::BindingResource::TextureView(out.view) },
                            wgpu::BindGroupEntry { binding: 1, resource: ubuf.as_entire_binding() },
                        ],
                    });
                    let mut pass = enc.begin_render_pass(&wgpu::RenderPassDescriptor {
                        label: Some("pc_encode"),
                        color_attachments: &[Some(wgpu::RenderPassColorAttachment {
                            view: target,
                            resolve_target: None,
                            depth_slice: None,
                            ops: wgpu::Operations { load: wgpu::LoadOp::Load, store: wgpu::StoreOp::Store },
                        })],
                        depth_stencil_attachment: None,
                        timestamp_writes: None,
                        occlusion_query_set: None,
                        multiview_mask: None,
                    });
                    pass.set_pipeline(pipe);
                    pass.set_bind_group(0, &bg, &[]);
                    pass.set_scissor_rect((r.x0 - tx) as u32, (r.y0 - ty) as u32, r.width(), r.height());
                    pass.draw(0..3, 0..1);
                }
            })
        }));
        let Ok(result) = result else {
            self.health.mark(photocraft_gpu::Fault::Lost("the GPU compositor stopped (internal error)".into()));
            res.docs.remove(&key);
            return Err(photocraft_gpu::Unsupported("GPU device lost".into()));
        };
        // Lost during the refresh: its output can't be trusted.
        let result = match self.fault() {
            Some(f) => Err(photocraft_gpu::Unsupported(f.to_string())),
            None => result,
        };
        if result.is_ok() {
            d.regenerate_mips_from(device, queue, res, [region.x0 as u32, region.y0 as u32, region.x1 as u32, region.y1 as u32], level);
            self.pace.submitted(queue);
            if std::env::var_os("PHOTOCRAFT_GPU_SYNC").is_some() {
                // Benchmarking: wait for the GPU so callers can time the whole refresh.
                #[cfg(not(target_arch = "wasm32"))]
                self.health.wait(device, None);
            }
        } else if fresh {
            res.docs.remove(&key);
        }
        res.compositor = Some(comp);
        result
    }

    /// Bring document `key`'s display texture up to date with `doc`: only `damage` when given (a
    /// brush stroke on an already uploaded document), else everything. The wgpu compositor renders
    /// straight into the texture when it supports the document; otherwise the CPU compositor does.
    /// `display` is the canvas colour transform: the GPU path stores the sRGB encoding when it
    /// asks for it, and every CPU band or rect goes through its `texture_buffer`.
    pub fn refresh(
        &self,
        key: u64,
        doc: &photocraft_doc::Document,
        damage: Option<photocraft_geom::Rect>,
        display: Option<&photocraft_engine::display_color::CanvasDisplay>,
    ) -> Refresh {
        self.refresh_for(key, doc, damage, display, None)
    }

    /// [`GpuCanvas::refresh`] for a view that shows `need`: on the wgpu compositor only the part
    /// of the change near what the view shows is composited now, at the view's mip level when
    /// it is zoomed out and the change is large ([`LOD_MIN_PX`]); the rest is marked out of
    /// date and brought up to date by [`GpuCanvas::catch_up`] (when the view needs it, or at
    /// full size once the edits pause).
    pub fn refresh_for(
        &self,
        key: u64,
        doc: &photocraft_doc::Document,
        damage: Option<photocraft_geom::Rect>,
        display: Option<&photocraft_engine::display_color::CanvasDisplay>,
        need: Option<ViewNeed>,
    ) -> Refresh {
        if let Some(f) = self.fault() {
            // Nothing reaches the GPU any more; the app switches to the CPU canvas.
            return Refresh { kind: "lost", fallback: Some(f.to_string()), ..Default::default() };
        }
        if !self.fits_canvas(doc) {
            // Neither compositor can fill textures that are never created: the CPU canvas draws
            // it. A set left from before the canvas grew is stale, so it goes too.
            if let Some(res) = self.rs.renderer.write().callback_resources.get_mut::<StoredResources>() {
                res.docs.remove(&key);
            }
            return Refresh { kind: REFRESH_OVER_BUDGET, fallback: Some(OVER_CANVAS_BUDGET.into()), ..Default::default() };
        }
        let bounds = doc.bounds();
        let size = [doc.size.width, doc.size.height];
        let format = self.format_for(doc.depth, size);
        let damage = damage.filter(|_| self.has(key, size) && self.format_of(key) == Some(format)).map(|r| r.intersect(&bounds));
        let t0 = now_ms();
        let mut out = Refresh::default();
        if damage.is_some_and(|r| r.is_empty()) {
            // Nothing changed on the canvas (selecting a layer, say): don't even plan.
            out.kind = "rect";
            return out;
        }
        let region = damage.unwrap_or(bounds);
        let encode_srgb = display.is_some_and(|d| d.encode_srgb);
        let gpu = if key != doc.id.0 {
            Err(photocraft_gpu::Unsupported("preview texture".into()))
        } else if let Some(n) = need {
            let near = near_view(n.visible, bounds);
            let now = region.intersect(&near);
            let later = subtract(region, near);
            let level = if area(now) >= LOD_MIN_PX { n.level } else { 0 };
            let r = self.composite_lod(doc, now, encode_srgb, level, true);
            if let Ok(stats) = &r {
                self.with_doc(key, |res, d| {
                    let mut stale = d.stale();
                    for p in &later {
                        stale.defer(*p);
                    }
                    if stats.level > 0 || !later.is_empty() {
                        res.reduced_at = now_ms();
                    }
                    res.last_passes = stats.passes;
                });
            }
            r
        } else {
            self.composite(doc, region, encode_srgb)
        };
        match gpu {
            Ok(stats) => {
                out.kind = if damage.is_some() { "gpu-rect" } else { "gpu-full" };
                out.px = stats.pixels;
                out.level = stats.level;
                out.composite_ms = now_ms() - t0;
                out.uploads = stats.tiles_uploaded as u64;
                return out;
            }
            Err(e) => out.fallback = Some(e.0),
        }
        if let Some(r) = damage {
            if r.is_empty() {
                out.kind = "rect";
                return out;
            }
            let buf = photocraft_compose::render(doc, r);
            let t1 = now_ms();
            if self.upload_buffer_rect(key, &texture_buffer(display, &buf)) {
                out.kind = "rect";
                out.px = r.width() as u64 * r.height() as u64;
                out.composite_ms = t1 - t0;
                out.upload_ms = now_ms() - t1;
                return out;
            }
        }
        self.upload_composite(key, doc, display);
        out.kind = "full";
        out.px = bounds.width() as u64 * bounds.height() as u64;
        out.composite_ms = now_ms() - t0;
        out
    }

    /// Bring what view `need` shows of document `key` up to date (regions an earlier
    /// [`GpuCanvas::refresh_for`] deferred or composited at a coarser level than the view now
    /// samples), then, when `idle` and no reduced refresh happened for [`REFINE_DELAY_MS`], one
    /// piece of the remaining out-of-date regions at full size ([`REFINE_WORK`]). Call it on
    /// frames where the document didn't change; repaint again after [`CatchUp::again_ms`].
    pub fn catch_up(
        &self,
        key: u64,
        doc: &photocraft_doc::Document,
        display: Option<&photocraft_engine::display_color::CanvasDisplay>,
        need: ViewNeed,
        idle: bool,
        ctx: &egui::Context,
    ) -> CatchUp {
        let mut out = CatchUp::default();
        if key != doc.id.0 || self.fault().is_some() || !self.has(key, [doc.size.width, doc.size.height]) {
            return out;
        }
        let bounds = doc.bounds();
        let near = near_view(need.visible, bounds);
        let Some((urgent, reduced_at, passes)) = self.with_doc(key, |res, d| (d.stale().needed(near, need.level), res.reduced_at, res.last_passes)) else {
            return out;
        };
        let encode_srgb = display.is_some_and(|d| d.encode_srgb);
        let t0 = now_ms();
        if PACE_COMPOSITES && !urgent.is_empty() && self.busy() {
            // Wait for the composite on the GPU (its completion asks for the frame).
            self.wake_when_done(ctx);
            return out;
        }
        for r in urgent {
            let level = if area(r) >= LOD_MIN_PX { need.level } else { 0 };
            match self.composite_lod(doc, r, encode_srgb, level, true) {
                Ok(st) => out.px += st.pixels,
                Err(_) => {
                    // Not on the GPU any more: the next refresh redraws the document.
                    self.forget_doc(key);
                    return out;
                }
            }
        }
        let wait = REFINE_DELAY_MS - (now_ms() - reduced_at);
        // One refinement piece on the GPU at a time, sized from how long the last one took
        // there (submit to completion): the frames stay short on a slow GPU, pieces grow on a
        // fast one.
        #[cfg(not(target_arch = "wasm32"))]
        let _ = self.rs.device.poll(wgpu::PollType::Poll);
        let (busy, work) = self.refine.next_work();
        if idle && wait <= 0.0 && !busy {
            let budget = (work / passes.max(1) as u64).max(128 * 128);
            if let Some(piece) = self.with_doc(key, |_, d| d.stale().next_piece(need.visible, budget)).flatten() {
                self.rs.queue.on_submitted_work_done(self.refine.before());
                match self.composite_lod(doc, piece, encode_srgb, 0, true) {
                    Ok(st) => {
                        out.px += st.pixels;
                        out.refined = true;
                        let timer = self.refine.start();
                        // The next piece goes when this one is done (no frames in between: they
                        // would only queue more GPU work behind it).
                        // The browser runs the callback on the main thread, where the context
                        // lives (the threads build needs the wrapper to call it Send).
                        #[cfg(all(target_arch = "wasm32", target_feature = "atomics"))]
                        let wake = send_wrapper::SendWrapper::new(ctx.clone());
                        #[cfg(not(all(target_arch = "wasm32", target_feature = "atomics")))]
                        let wake = ctx.clone();
                        self.rs.queue.on_submitted_work_done(move || {
                            timer();
                            wake.request_repaint();
                        });
                    }
                    Err(_) => {
                        self.forget_doc(key);
                        return out;
                    }
                }
            }
        }
        out.composite_ms = now_ms() - t0;
        let pending = self.with_doc(key, |_, d| !d.stale().is_empty()).unwrap_or(false);
        // While a piece runs, its completion asks for the next frame.
        let running = out.refined || busy;
        out.again_ms = (pending && !running).then_some(wait.max(0.0));
        out
    }

    /// The finest mip level current everywhere in `visible` (0: all of it), for
    /// [`ViewParams::min_lod`]. Deferred regions (nothing current) don't count: the view
    /// catches up on them before it draws.
    pub fn view_floor(&self, key: u64, visible: photocraft_geom::Rect) -> f32 {
        self.with_doc(key, |_, d| d.stale().floor(visible)).unwrap_or(0) as f32
    }

    /// Whether a document composite is still running on the GPU (submitted less than
    /// [`BUSY_LIMIT_MS`] ago and not finished): callers then [`GpuCanvas::defer`] the next edit.
    pub fn busy(&self) -> bool {
        #[cfg(not(target_arch = "wasm32"))]
        let _ = self.rs.device.poll(wgpu::PollType::Poll);
        self.pace.busy()
    }

    /// Leave `r` of document `key`'s texture out of date: [`GpuCanvas::catch_up`] composites it
    /// on a later frame (at once where the view shows it).
    pub fn defer(&self, key: u64, r: photocraft_geom::Rect) {
        self.with_doc(key, |_, d| d.stale().defer(r));
    }

    /// Ask `ctx` for a frame once the GPU has finished everything queued so far.
    pub fn wake_when_done(&self, ctx: &egui::Context) {
        #[cfg(all(target_arch = "wasm32", target_feature = "atomics"))]
        let wake = send_wrapper::SendWrapper::new(ctx.clone());
        #[cfg(not(all(target_arch = "wasm32", target_feature = "atomics")))]
        let wake = ctx.clone();
        self.on_done(move || wake.request_repaint());
    }

    /// Whether document `key`'s texture has out-of-date regions (tests and diagnostics).
    pub fn has_stale(&self, key: u64) -> bool {
        self.with_doc(key, |_, d| !d.stale().is_empty()).unwrap_or(false)
    }

    fn with_doc<T>(&self, key: u64, f: impl FnOnce(&mut Resources, &DocTextures) -> T) -> Option<T> {
        let mut r = self.rs.renderer.write();
        let res: &mut Resources = r.callback_resources.get_mut::<StoredResources>()?;
        let d = res.docs.remove(&key)?;
        let out = f(res, &d);
        res.docs.insert(key, d);
        Some(out)
    }

    fn forget_doc(&self, key: u64) {
        if let Some(res) = self.rs.renderer.write().callback_resources.get_mut::<StoredResources>() {
            res.docs.remove(&key);
        }
    }

    /// Composite the whole of `doc` with the CPU compositor into document `key`'s texture, band by
    /// band (each band converted and uploaded before the next is rendered), so a huge document
    /// never needs a full-size float composite or texture-format copy in memory.
    pub fn upload_composite(&self, key: u64, doc: &photocraft_doc::Document, display: Option<&photocraft_engine::display_color::CanvasDisplay>) {
        let size = [doc.size.width, doc.size.height];
        if size[0] == 0 || size[1] == 0 || !self.health.is_ok() {
            return;
        }
        let format = self.format_for(doc.depth, size);
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        {
            let mut renderer = self.rs.renderer.write();
            let Some(res) = renderer.callback_resources.get_mut::<StoredResources>() else { return };
            if res.docs.get(&key).is_none_or(|d| d.size != size || d.format != format) {
                let Some(tex) = DocTextures::new(device, res, size, self.tile, format) else {
                    res.docs.remove(&key);
                    return;
                };
                res.docs.insert(key, tex);
            }
        }
        let mut rgba = Vec::new();
        let _ = photocraft_compose::render_bands(doc, doc.bounds(), 0, |band| -> Result<(), ()> {
            if !self.health.is_ok() {
                return Err(());
            }
            texels_into(format, &texture_buffer(display, &band).px, &mut rgba);
            let renderer = self.rs.renderer.read();
            let d = renderer.callback_resources.get::<StoredResources>().and_then(|r| r.docs.get(&key)).ok_or(())?;
            d.write(queue, [0, band.rect.y0 as u32], [size[0], band.rect.height()], size[0], &rgba);
            drop(renderer);
            // Flush the staged band so its staging memory is reclaimed while the next renders.
            queue.submit(std::iter::empty::<wgpu::CommandBuffer>());
            self.health.poll(device);
            Ok(())
        });
        if !self.health.is_ok() {
            return;
        }
        let mut renderer = self.rs.renderer.write();
        if let Some(res) = renderer.callback_resources.get_mut::<StoredResources>()
            && let Some(d) = res.docs.get(&key)
        {
            d.regenerate_mips(device, queue, res, [0, 0, size[0], size[1]]);
        }
    }

    /// Free textures, display LUTs and their signatures for documents not in `live`.
    pub fn retain(&self, live: &[u64]) {
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<StoredResources>() else { return };
        if res.docs.keys().any(|k| !live.contains(k)) {
            let gone: Vec<u64> = res.docs.keys().filter(|k| !live.contains(k)).copied().collect();
            if let Some(c) = res.compositor.as_mut() {
                for k in &gone {
                    c.forget_doc(photocraft_doc::DocId(*k));
                }
            }
            res.docs.retain(|k, _| live.contains(k));
        }
        // LUTs and identity-transform signatures can outlive document textures. Prune both,
        // or a preserved-ID reopen can skip rebuilding a missing LUT.
        res.luts.retain(|k, _| live.contains(&k.0));
        res.display_lut_signatures.retain(|k, _| live.contains(&k.0));
    }

    pub(crate) fn display_lut_signature(&self, doc: u64, output: u32) -> Option<(u64, u8)> {
        let renderer = self.rs.renderer.read();
        renderer.callback_resources.get::<StoredResources>()?.display_lut_signatures.get(&(doc, output)).copied()
    }

    /// Whether document `doc` has a display LUT for display `output` (tests).
    #[cfg(test)]
    pub(crate) fn has_display_lut(&self, doc: u64, output: u32) -> bool {
        let renderer = self.rs.renderer.read();
        renderer.callback_resources.get::<StoredResources>().is_some_and(|r| r.luts.contains_key(&(doc, output)))
    }

    pub(crate) fn cache_display_lut_signature(&self, doc: u64, output: u32, signature: u64, mode: u8) {
        let mut renderer = self.rs.renderer.write();
        if let Some(res) = renderer.callback_resources.get_mut::<StoredResources>() {
            res.display_lut_signatures.insert((doc, output), (signature, mode));
        }
    }

    /// Set (or clear with `None`) the display LUT of document `doc` on display `output`:
    /// `size`³ RGBA8 texels, red fastest. RGB is the display colour for each lattice input;
    /// alpha 255 marks out-of-gamut colours for the gamut warning.
    pub fn set_display_lut(&self, doc: u64, output: u32, size: u32, rgba: Option<&[u8]>) {
        if !self.health.is_ok() {
            return;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<StoredResources>() else { return };
        res.display_lut_signatures.remove(&(doc, output));
        match rgba {
            None => {
                res.luts.remove(&(doc, output));
            }
            Some(bytes) => {
                if size < 2 || bytes.len() as u64 != (size as u64).pow(3) * 4 {
                    log::warn!("set_display_lut: {} bytes for a {size}³ LUT; ignored", bytes.len());
                    return;
                }
                let bg = lut_bind_group(device, queue, &res.lut_bgl, size, bytes);
                res.luts.insert((doc, output), bg);
            }
        }
    }

    /// Read back level 0 of document `key`'s canvas texture: its format, size and the stored
    /// (premultiplied) texels as `f32` RGBA, row-major. Waits for the GPU; for tests, benchmarks
    /// and debugging.
    #[cfg(not(target_arch = "wasm32"))]
    pub fn read_texels(&self, key: u64) -> Option<(wgpu::TextureFormat, [u32; 2], Vec<[f32; 4]>)> {
        self.read_texels_level(key, 0)
    }

    /// [`GpuCanvas::read_texels`] of mip level `level` (its size is the level's).
    #[cfg(not(target_arch = "wasm32"))]
    pub fn read_texels_level(&self, key: u64, level: u32) -> Option<(wgpu::TextureFormat, [u32; 2], Vec<[f32; 4]>)> {
        if !self.health.is_ok() {
            return None;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let renderer = self.rs.renderer.read();
        let d = renderer.callback_resources.get::<StoredResources>()?.docs.get(&key)?;
        let bpp = texel_bytes(d.format);
        let (w, h) = ((d.size[0] >> level).max(1) as usize, (d.size[1] >> level).max(1) as usize);
        let mut out = vec![[0.0f32; 4]; w.checked_mul(h)?];
        for t in &d.tiles {
            if level as usize >= t.levels.len() {
                return None;
            }
            let [tx, ty, tw, th] = [t.rect[0] >> level, t.rect[1] >> level, (t.rect[2] >> level).max(1), (t.rect[3] >> level).max(1)];
            let row = (tw as u64 * bpp).next_multiple_of(wgpu::COPY_BYTES_PER_ROW_ALIGNMENT as u64);
            let buf = device.create_buffer(&wgpu::BufferDescriptor {
                label: Some("pc_canvas_readback"),
                size: row * th as u64,
                usage: wgpu::BufferUsages::COPY_DST | wgpu::BufferUsages::MAP_READ,
                mapped_at_creation: false,
            });
            let mut enc = device.create_command_encoder(&wgpu::CommandEncoderDescriptor { label: Some("pc_canvas_readback") });
            enc.copy_texture_to_buffer(
                wgpu::TexelCopyTextureInfo { texture: &t.texture, mip_level: level, origin: wgpu::Origin3d::ZERO, aspect: wgpu::TextureAspect::All },
                wgpu::TexelCopyBufferInfo {
                    buffer: &buf,
                    layout: wgpu::TexelCopyBufferLayout { offset: 0, bytes_per_row: Some(row as u32), rows_per_image: Some(th) },
                },
                wgpu::Extent3d { width: tw, height: th, depth_or_array_layers: 1 },
            );
            queue.submit([enc.finish()]);
            let slice = buf.slice(..);
            slice.map_async(wgpu::MapMode::Read, |_| {});
            if !self.health.wait(device, None) {
                return None;
            }
            let data = slice.get_mapped_range().ok()?;
            for y in 0..th as usize {
                let src = data.get(y * row as usize..)?;
                for x in 0..tw as usize {
                    let o = out.get_mut((ty as usize + y) * w + tx as usize + x)?;
                    *o = texel_to_f32(d.format, src.get(x * bpp as usize..(x + 1) * bpp as usize)?);
                }
            }
        }
        Some((d.format, [w as u32, h as u32], out))
    }

    /// Add the paint callback drawing `params` into `rect` (clipped by the painter's clip rect).
    pub fn paint(painter: &egui::Painter, rect: egui::Rect, params: ViewParams) {
        painter.add(egui_wgpu::Callback::new_paint_callback(rect, CanvasCallback { rect, params }));
    }
}

